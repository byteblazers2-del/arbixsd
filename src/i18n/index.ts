/**
 * Resolves user language strictly between English (en), Russian (ru), and Chinese (zh)
 */
export function resolveUserLanguage(rawCode?: string | null): LanguageCode {
  if (rawCode) {
    const clean = rawCode.toLowerCase().trim();
    if (clean.startsWith('zh') || clean.startsWith('cn')) return 'zh';
    if (clean.startsWith('ru')) return 'ru';
    if (clean.startsWith('en')) return 'en';
  }

  if (typeof window !== 'undefined' && window.location) {
    try {
      const searchParams = new URLSearchParams(window.location.search);
      const urlLang = searchParams.get('lang') || searchParams.get('language_code');
      if (urlLang) {
        const u = urlLang.toLowerCase().trim();
        if (u.startsWith('zh') || u.startsWith('cn')) return 'zh';
        if (u.startsWith('ru')) return 'ru';
        return 'en';
      }
    } catch {}
  }

  try {
    const saved = localStorage.getItem('app_lang');
    if (saved && (saved === 'zh' || saved === 'ru' || saved === 'en')) {
      return saved as LanguageCode;
    }
  } catch {}

  try {
    const tgLang = (window as any).Telegram?.WebApp?.initDataUnsafe?.user?.language_code;
    if (tgLang) {
      const t = String(tgLang).toLowerCase().trim();
      if (t.startsWith('zh') || t.startsWith('cn')) return 'zh';
      if (t.startsWith('ru')) return 'ru';
    }
  } catch {}

  try {
    const navLang = navigator.language || (navigator.languages && navigator.languages[0]);
    if (navLang) {
      const n = navLang.toLowerCase().trim();
      if (n.startsWith('zh') || n.startsWith('cn')) return 'zh';
      if (n.startsWith('ru')) return 'ru';
    }
  } catch {}

  return 'en';
}

